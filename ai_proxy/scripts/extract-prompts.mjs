/**
 * 从 Dart 源码抽取各板块的系统提示词，生成 src/prompts.gen.js。
 *
 * 为什么要生成而不是手抄：提示词动辄上百行中文，手抄必然引入错字/漏行。
 * 以 lib/core/network/ai_api_client.dart 为唯一事实来源，跑一次脚本即可
 * 把服务端 registry 与客户端保持同步。
 *
 * 用法：node scripts/extract-prompts.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DART = resolve(here, '../../lib/core/network/ai_api_client.dart');
const OUT = resolve(here, '../src/prompts.gen.js');

/** Dart 常量名 → X-Board 键。 */
const MAP = {
  wrongQuestion: 'wrongQuestion',
  expert: 'expert',
  followUp: 'followUp',
  exam: 'exam',
  qa: 'qa',
  report: 'report',
};

const source = readFileSync(DART, 'utf8');

/** 匹配 static const String _fooSystemPrompt = ''' ... '''; */
const re = /static const String _(\w+?)SystemPrompt\s*=\s*r?'''([\s\S]*?)''';/g;

const prompts = {};
let match;
while ((match = re.exec(source)) !== null) {
  const dartName = match[1];
  const board = MAP[dartName];
  if (!board) continue;
  // Dart 普通字符串里 \$ 是转义的美元号（raw 字符串无需处理）。
  prompts[board] = match[2].replace(/\\\$/g, '$');
}

const found = Object.keys(prompts);
const missing = Object.values(MAP).filter((b) => !found.includes(b));
if (missing.length) {
  console.error(`[extract-prompts] 未找到以下板块的提示词: ${missing.join(', ')}`);
  process.exit(1);
}

const banner =
  '// AUTO-GENERATED by scripts/extract-prompts.mjs — 请勿手改。\n' +
  '// 来源: lib/core/network/ai_api_client.dart\n';

const body =
  'export const PROMPTS = ' +
  JSON.stringify(prompts, null, 2) +
  ';\n';

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner + body, 'utf8');

console.log(
  `[extract-prompts] 已写出 ${OUT}，板块: ${found.join(', ')}`,
);
